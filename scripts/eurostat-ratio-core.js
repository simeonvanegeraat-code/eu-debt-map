const fs = require("node:fs");

const {
  EU27,
  compareQuarters,
  extractExportJson,
  normalizeQuarterKey,
  parseEurostatDataset,
} = require("./eurostat-debt-core");

const HISTORY_LIMIT = 8;
const MAX_REASONABLE_RATIO_PCT = 500;

const toEurostatGeo = (code) => (code === "GR" ? "EL" : code);

function normalizeExistingRatioRow(row) {
  if (!row || typeof row !== "object") return null;

  const latestTime = normalizeQuarterKey(row.latestTime);
  const ratioPct = Number(row.ratioPct);
  if (
    !latestTime ||
    !Number.isFinite(ratioPct) ||
    ratioPct <= 0 ||
    ratioPct > MAX_REASONABLE_RATIO_PCT
  ) {
    return null;
  }

  return { latestTime, ratioPct };
}

function periodSummary(series) {
  const counts = {};
  for (const code of EU27) {
    const period = normalizeQuarterKey(series?.[code]?.latestTime);
    if (!period) continue;
    counts[period] = (counts[period] || 0) + 1;
  }

  const entries = Object.entries(counts).sort((a, b) => {
    if (b[1] !== a[1]) return b[1] - a[1];
    return compareQuarters(b[0], a[0]);
  });

  return {
    periodCounts: counts,
    dominantLatestTime: entries[0]?.[0] || null,
    dominantCoverage: entries[0]?.[1] || 0,
    latestAvailableTime: Object.keys(counts).sort(compareQuarters).at(-1) || null,
  };
}

function buildRatioSeries(parsed, previousSeries = {}) {
  const series = {};
  const acceptedCodes = [];
  const carriedForwardCodes = [];
  const regressedSourceCodes = [];
  const missingCodes = [];

  for (const code of EU27) {
    const previousRow = normalizeExistingRatioRow(previousSeries?.[code]);
    const points = Object.entries(parsed.valuesByCountry?.[code] || {})
      .map(([quarter, ratioPct]) => ({
        latestTime: normalizeQuarterKey(quarter),
        ratioPct: Number(ratioPct),
      }))
      .map(normalizeExistingRatioRow)
      .filter(Boolean)
      .sort((a, b) => compareQuarters(a.latestTime, b.latestTime));

    if (points.length === 0) {
      if (previousRow) {
        series[code] = previousRow;
        carriedForwardCodes.push(code);
      } else {
        missingCodes.push(code);
      }
      continue;
    }

    const latest = points.at(-1);
    if (previousRow && compareQuarters(latest.latestTime, previousRow.latestTime) < 0) {
      series[code] = previousRow;
      carriedForwardCodes.push(code);
      regressedSourceCodes.push(code);
      continue;
    }

    series[code] = latest;
    acceptedCodes.push(code);
  }

  const summary = periodSummary(series);
  const staleCodes = EU27.filter((code) => {
    const period = series?.[code]?.latestTime;
    return (
      period &&
      summary.dominantLatestTime &&
      compareQuarters(period, summary.dominantLatestTime) < 0
    );
  });

  return {
    series,
    report: {
      ...summary,
      acceptedCodes,
      carriedForwardCodes,
      regressedSourceCodes,
      missingCodes,
      staleCodes,
      sourceMissingGeoKeys: parsed.missingGeoKeys || [],
      sourceUnknownGeoKeys: parsed.unknownGeoKeys || [],
    },
  };
}

function validateRatioSeries(series) {
  const codes = Object.keys(series || {});
  const missing = EU27.filter((code) => !codes.includes(code));
  const extra = codes.filter((code) => !EU27.includes(code));
  const invalid = EU27.filter((code) => !normalizeExistingRatioRow(series?.[code]));

  if (missing.length || extra.length || invalid.length) {
    throw new Error(
      `Invalid debt-to-GDP snapshot (missing: ${missing.join(",") || "none"}; ` +
        `extra: ${extra.join(",") || "none"}; invalid: ${invalid.join(",") || "none"})`
    );
  }
  return true;
}

function readRatioGenerated(file) {
  if (!fs.existsSync(file)) {
    return { source: null, snapshotId: null, updatedAt: null, report: {}, series: {} };
  }

  const source = fs.readFileSync(file, "utf8");
  return {
    source,
    snapshotId: extractExportJson(source, "EUROSTAT_RATIO_SNAPSHOT_ID", null),
    updatedAt: extractExportJson(source, "EUROSTAT_RATIO_UPDATED_AT", null),
    report: extractExportJson(source, "EUROSTAT_RATIO_UPDATE_REPORT", {}),
    series: extractExportJson(source, "EUROSTAT_RATIO_SERIES", {}),
  };
}

function renderRatioGenerated({ snapshotId, updatedAt, report, series }) {
  return (
    `// Auto-generated by scripts/update-eurostat-ratios.js\n` +
    `export const EUROSTAT_RATIO_SNAPSHOT_ID = ${JSON.stringify(snapshotId)};\n` +
    `export const EUROSTAT_RATIO_UPDATED_AT = ${JSON.stringify(updatedAt)};\n` +
    `export const EUROSTAT_RATIO_UPDATE_REPORT = ${JSON.stringify(report, null, 2)};\n` +
    `export const EUROSTAT_RATIO_SERIES = ${JSON.stringify(series, null, 2)};\n`
  );
}

function buildRatioEurostatUrl(lastTimePeriod = HISTORY_LIMIT) {
  const base =
    "https://ec.europa.eu/eurostat/api/dissemination/statistics/1.0/data/gov_10q_ggdebt";
  const params = new URLSearchParams({
    lang: "EN",
    format: "JSON",
    freq: "Q",
    sector: "S13",
    na_item: "GD",
    unit: "PC_GDP",
    lastTimePeriod: String(lastTimePeriod),
  });
  for (const code of EU27) params.append("geo", toEurostatGeo(code));
  return `${base}?${params.toString()}`;
}

module.exports = {
  MAX_REASONABLE_RATIO_PCT,
  buildRatioEurostatUrl,
  buildRatioSeries,
  normalizeExistingRatioRow,
  parseEurostatDataset,
  periodSummary,
  readRatioGenerated,
  renderRatioGenerated,
  validateRatioSeries,
};
